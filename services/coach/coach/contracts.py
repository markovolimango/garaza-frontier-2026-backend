"""Generate contracts/: JSON Schemas, OpenAPI and TypeScript types (python -m coach contracts)."""

from __future__ import annotations

import json
import re
from pathlib import Path

from pydantic import BaseModel, TypeAdapter

from coach import SCHEMA_VERSION
from coach.config import SessionConfig, Settings
from coach import wire, wsmessages as ws

HEADER = "// GENERATED by `python -m coach contracts` from services/coach/coach/wire.py and wsmessages.py. Do not edit.\n"


def _models() -> dict[str, type[BaseModel]]:
    models = {
        "EventIn": wire.EventIn, "EventOut": wire.EventOut, "Source": wire.Source, "Timing": wire.Timing,
        "ErrorEnvelope": wire.ErrorEnvelope, "SessionCreate": wire.SessionCreate,
        "CalibrationRequest": wire.CalibrationRequest, "PairRequest": wire.PairRequest,
        "SessionConfig": SessionConfig,
    }
    for etype, model in {**wire.PAYLOAD_MODELS, **wire.SERVER_PAYLOAD_MODELS}.items():
        models[model.__name__] = model
    for model in ws.INGEST_CLIENT + ws.INGEST_SERVER + ws.STREAM_CLIENT + ws.STREAM_SERVER + [ws.AckResult]:
        models[model.__name__] = model
    return models


def write_contracts(out: Path) -> list[Path]:
    written: list[Path] = []
    schemas_dir = out / "schemas"
    schemas_dir.mkdir(parents=True, exist_ok=True)
    models = _models()
    for name, model in sorted(models.items()):
        schema = model.model_json_schema()
        schema["$id"] = f"https://garaza-frontier.local/schemas/{SCHEMA_VERSION}/{name}.schema.json"
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        path = schemas_dir / f"{name}.schema.json"
        path.write_text(json.dumps(schema, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        written.append(path)
    index = {
        "schema_version": SCHEMA_VERSION,
        "event_payloads": {e.value: m.__name__ for e, m in {**wire.PAYLOAD_MODELS, **wire.SERVER_PAYLOAD_MODELS}.items()},
        "device_event_types": sorted(e.value for e in wire.DEVICE_EVENT_TYPES),
        "server_event_types": sorted(e.value for e in wire.SERVER_EVENT_TYPES),
        "ingest": {"client": [m.__name__ for m in ws.INGEST_CLIENT], "server": [m.__name__ for m in ws.INGEST_SERVER]},
        "stream": {"client": [m.__name__ for m in ws.STREAM_CLIENT], "server": [m.__name__ for m in ws.STREAM_SERVER]},
    }
    (schemas_dir / "index.json").write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
    written.append(schemas_dir / "index.json")

    from coach.api import create_app
    settings = Settings()
    settings.api_token = "contract-generation"
    settings.assistant_enabled = False
    openapi = create_app(settings, start_background=False).openapi()
    (out / "openapi.json").write_text(json.dumps(openapi, indent=2) + "\n", encoding="utf-8")
    written.append(out / "openapi.json")

    ts_dir = out / "typescript"
    ts_dir.mkdir(parents=True, exist_ok=True)
    ts = _typescript(models, index)
    (ts_dir / "coach-types.ts").write_text(ts, encoding="utf-8")
    written.append(ts_dir / "coach-types.ts")
    return written


# ----------------------------------------------------------------------- TypeScript
def _ts_type(schema: dict, defs: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts_type(s, defs) for s in schema["anyOf"]))
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("number", "integer"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = _ts_type(schema.get("items", {}), defs)
        return f"Array<{inner}>"
    if kind == "object" and "properties" not in schema:
        extra = schema.get("additionalProperties")
        value = _ts_type(extra, defs) if isinstance(extra, dict) and extra else "unknown"
        return f"Record<string, {value}>"
    if kind == "object":
        return _ts_object(schema, defs)
    return "unknown"


def _ts_object(schema: dict, defs: dict, indent: str = "  ") -> str:
    required = set(schema.get("required", []))
    lines = ["{"]
    for prop, sub in schema.get("properties", {}).items():
        doc = sub.get("description")
        if doc:
            lines.append(f"{indent}/** {doc} */")
        optional = "" if prop in required else "?"
        lines.append(f"{indent}{prop}{optional}: {_ts_type(sub, defs)};")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


def _typescript(models: dict[str, type[BaseModel]], index: dict) -> str:
    out = [HEADER, f'export const SCHEMA_VERSION = "{SCHEMA_VERSION}";\n']
    emitted: dict[str, str] = {}
    for name, model in sorted(models.items()):
        schema = model.model_json_schema()
        for def_name, definition in schema.get("$defs", {}).items():
            if def_name not in emitted:
                emitted[def_name] = _ts_decl(def_name, definition, schema.get("$defs", {}))
        emitted[name] = _ts_decl(name, schema, schema.get("$defs", {}))
    out += [emitted[k] for k in sorted(emitted)]
    payloads = index["event_payloads"]
    out.append("export interface EventPayloadMap {\n" + "\n".join(
        f'  "{etype}": {model};' for etype, model in sorted(payloads.items())) + "\n}\n")
    out.append("export type EventType = keyof EventPayloadMap;\n")
    out.append("/** A stream event with its payload typed by event_type. */\n"
               "export type TypedEvent<T extends EventType = EventType> = Omit<EventOut, \"event_type\" | \"payload\"> & "
               "{ event_type: T; payload: EventPayloadMap[T] };\n")
    for group, members in (("IngestClientMessage", index["ingest"]["client"]),
                           ("IngestServerMessage", index["ingest"]["server"]),
                           ("StreamClientMessage", index["stream"]["client"]),
                           ("StreamServerMessage", index["stream"]["server"])):
        out.append(f"export type {group} = " + " | ".join(members) + ";\n")
    return "\n".join(out)


def _ts_decl(name: str, schema: dict, defs: dict) -> str:
    doc = schema.get("description")
    prefix = f"/** {doc.strip().splitlines()[0]} */\n" if doc else ""
    if schema.get("type") == "object" and "properties" in schema:
        return f"{prefix}export interface {name} {_ts_object(schema, defs)}\n"
    return f"{prefix}export type {name} = {_ts_type(schema, defs)};\n"
